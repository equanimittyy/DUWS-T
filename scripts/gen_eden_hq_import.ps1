# gen_eden_hq_import.ps1  [originX] [originY]
#
# Emit a complete, paste-ready Eden import script for the HQ composition. Hand-copying the
# _allObjectsData array out of fnc_BluHQinit.sqf into the import boilerplate is error-prone:
# a missed paste silently imports only the HQ building. This extracts the array by PATTERN
# (not line number, which the export round-trip keeps changing) and the anchor from the
# source's own _hqInComp* values, wraps them in the placement loop, writes
# temp\eden_hq_import.sqf, and copies it to the clipboard. See docs/hq_layout_editing.md.
param(
    [double]$OriginX = 23100,
    [double]$OriginY = 18700
)
$ErrorActionPreference = "Stop"

# Script lives in scripts\; the source and temp\ are at the repo root (its parent).
$root = Split-Path -Parent $PSScriptRoot
$src  = Join-Path $root "src\duws\functions\init_hq\fnc_BluHQinit.sqf"
$out  = Join-Path $root "temp\eden_hq_import.sqf"

if (-not (Test-Path -LiteralPath $src)) { Write-Error "Source not found: $src"; exit 1 }
$lines = Get-Content -LiteralPath $src -Encoding UTF8

# The anchor the runtime subtracts from every object (the _hqInComp* values near the top).
$mx = $lines | Select-String -Pattern '_hqInCompX\s*=\s*([0-9.]+)' | Select-Object -First 1
$my = $lines | Select-String -Pattern '_hqInCompY\s*=\s*([0-9.]+)' | Select-Object -First 1
if (-not $mx -or -not $my) { Write-Error "Could not read _hqInCompX/Y from $src"; exit 1 }
$hqx = $mx.Matches[0].Groups[1].Value
$hqy = $my.Matches[0].Groups[1].Value

# The whole `private _allObjectsData = [ ... ];` block, verbatim.
$arr = New-Object System.Collections.Generic.List[string]
$inArray = $false
foreach ($line in $lines) {
    if ($line -match 'private _allObjectsData = \[') { $inArray = $true }
    if ($inArray) { $arr.Add($line) }
    if ($inArray -and $line -match '^\];') { break }
}
if ($arr.Count -eq 0) { Write-Error "Could not find _allObjectsData array in $src"; exit 1 }
$rows = ($arr | Where-Object { $_ -match '^\s*\["' }).Count

$prologue = @"
// RUN FROM THE EDEN DEBUG CONSOLE (3D editor toolbar > {}), not the in-game console.
// Generated by scripts\gen_eden_hq_import.ps1 from fnc_BluHQinit.sqf (do not hand-edit).
private _hqRef  = [$hqx, $hqy];   // HQ building's anchor coords, from the source
private _origin = [$OriginX, $OriginY, 0];   // where the HQ building lands in Eden; pick any flat spot
"@

$epilogue = @'
private _made = 0;
{
    _x params ["_class","_ox","_oy","_oz","_dir",["_isWeapon",false]];
    private _pos = [
        (_origin select 0) + (_ox - (_hqRef select 0)),
        (_origin select 1) + (_oy - (_hqRef select 1)),
        0
    ];
    private _ent = create3DENEntity ["Object", _class, _pos];
    _ent set3DENAttribute ["rotation", _dir];   // Objects: rotation is one Number (yaw)
    _made = _made + 1;
} forEach _allObjectsData;
hint format ["HQ import: created %1 of %2 objects.", _made, count _allObjectsData];
'@

$script = $prologue + "`r`n`r`n" + ($arr -join "`r`n") + "`r`n`r`n" + $epilogue

New-Item -ItemType Directory -Force -Path (Split-Path -Parent $out) | Out-Null
[System.IO.File]::WriteAllText($out, $script, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "[gen] Wrote $out ($rows objects, anchor [$hqx, $hqy], origin [$OriginX, $OriginY])."

try {
    Set-Clipboard -Value $script
    Write-Host "[gen] Copied to clipboard."
} catch {
    Write-Host "[gen] Clipboard unavailable; open the file and copy its contents."
}
